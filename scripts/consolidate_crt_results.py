"""Consolidated table of the CRT pilot results, generated from the saved JSON files.

Inputs (NE-EXP-002 folder):
  crt_pilot_v1_full100.json  v1 at 100 replicates, aggregates only (no per-replicate p values)
  crt_pilot_v1_n30.json      v1 configuration at 30 replicates, per-replicate p values
  crt_pilot_v2_n30.json      v2 at 30 replicates, per-replicate p values
Output: crt_consolidated_results.md

The 30-replicate runs share a seed and random stream, so their rows are paired (McNemar-type
discordant counts b and c). The 100-replicate run cannot be paired with them and is shown
as aggregates only.
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np

FOLDER = Path("experiments/20261027-ne-exp-002-temporal-latent-confounding")
ALPHA = 0.05
Z95 = 1.959963984540054


def wilson(k: int, n: int) -> tuple[float, float]:
    p = k / n
    denom = 1 + Z95 * Z95 / n
    centre = (p + Z95 * Z95 / (2 * n)) / denom
    half = Z95 * np.sqrt(p * (1 - p) / n + Z95 * Z95 / (4 * n * n)) / denom
    return float(centre - half), float(centre + half)


def fmt(k: int, n: int) -> str:
    lo, hi = wilson(k, n)
    return f"{k}/{n} [{lo:.3f}, {hi:.3f}]"


def main() -> None:
    full = json.loads((FOLDER / "crt_pilot_v1_full100.json").read_text(encoding="utf-8"))
    v1 = json.loads((FOLDER / "crt_pilot_v1_n30.json").read_text(encoding="utf-8"))
    v2 = json.loads((FOLDER / "crt_pilot_v2_n30.json").read_text(encoding="utf-8"))
    n_full, n30 = full["n_reps"], v1["n_reps"]
    assert n30 == v2["n_reps"] == 30 and v1["seed"] == v2["seed"] == full["seed"]

    lines = [
        "# Consolidated CRT pilot results (NE-EXP-002, synthetic only)",
        "",
        "Generated by `scripts/consolidate_crt_results.py` from the saved JSON files.",
        "Wilson 95% intervals.",
        "",
        "| scenario | kind | v1 full, 100 reps (aggregate) | v1 config, 30 reps "
        "| v2, 30 reps | paired b (v1 only) | paired c (v2 only) |",
        "|---|---|---|---|---|---|---|",
    ]
    for scen in v2["results"]:
        for kind in ("independent", "conditional"):
            k_full = full["results"][scen][kind]["rejections"]
            k1 = v1["results"][scen][kind]["rejections"]
            k2 = v2["results"][scen][kind]["rejections"]
            r1 = np.array(v1["results"][scen]["p_values"][kind]) <= ALPHA
            r2 = np.array(v2["results"][scen]["p_values"][kind]) <= ALPHA
            b = int(np.sum(r1 & ~r2))
            c = int(np.sum(~r1 & r2))
            row = f"| {scen} | {kind} | {fmt(k_full, n_full)} | {fmt(k1, n30)} "
            lines.append(row + f"| {fmt(k2, n30)} | {b} | {c} |")
    lines += [
        "",
        "Paired differences apply only to the two 30-replicate columns "
        "(same seed, same synthetic series).",
        "The 100-replicate column is not paired with them: its per-replicate p values "
        "were not saved.",
        "Agreement of the 30- and 100-replicate rates is consistent with sampling error at",
        "this precision; it is not a test of equivalence.",
    ]
    out = FOLDER / "crt_consolidated_results.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("saved", out)


if __name__ == "__main__":
    main()
